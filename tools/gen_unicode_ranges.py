#!/usr/bin/env python3
"""Regenerate src/unicode_data.h (\\p{L} and \\p{N} code point ranges).

The tokenizer's pre-tokenizer applies the model's two-stage regex split
(`\\p{N}{1,3}` and the GPT-4 style word regex), which needs Unicode general
category lookups. The tables are generated from Python's unicodedata so the
build has no runtime dependency on it.

Usage:  python3 tools/gen_unicode_ranges.py > /dev/null   (writes src/unicode_data.h)
"""
import os
import unicodedata

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "unicode_data.h")


def ranges(pred):
    out = []
    start = None
    prev = None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(unicodedata.category(chr(cp)))
        if ok:
            if start is None:
                start = cp
            prev = cp
        elif start is not None:
            out.append((start, prev))
            start = None
    if start is not None:
        out.append((start, prev))
    return out


def emit(name, rs):
    lines = ["static const uint32_t %s[][2] = {" % name]
    row = []
    for a, b in rs:
        row.append("{0x%X,0x%X}" % (a, b))
        if len(row) == 4:
            lines.append("  " + ",".join(row) + ",")
            row = []
    if row:
        lines.append("  " + ",".join(row) + ",")
    lines.append("};")
    lines.append("static constexpr size_t %s_count = sizeof(%s)/sizeof(%s[0]);" % (name, name, name))
    return "\n".join(lines)


def main():
    letters = ranges(lambda c: c[0] == "L")
    numbers = ranges(lambda c: c[0] == "N")
    src = """// Generated by tools/gen_unicode_ranges.py (Python unicodedata %s).
// Code point ranges with Unicode general category L* (\\p{L}) and N* (\\p{N}),
// used by the tokenizer's pre-tokenizer regex splits.
#pragma once
#include <cstdint>
#include <cstddef>

namespace exl3 {
namespace uni {

%s

%s

} // namespace uni
} // namespace exl3
""" % (unicodedata.unidata_version, emit("kLetterRanges", letters), emit("kNumberRanges", numbers))
    with open(OUT, "w") as f:
        f.write(src)
    print("wrote %s (%d letter ranges, %d number ranges)" % (OUT, len(letters), len(numbers)))


if __name__ == "__main__":
    main()
